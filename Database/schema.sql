CREATE TABLE IF NOT EXISTS bus_stops (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stop_number SMALLINT NOT NULL UNIQUE CHECK (stop_number BETWEEN 1 AND 999),
  name TEXT NOT NULL CHECK (length(trim(name)) > 0),
  latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
  longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
  srid SMALLINT NOT NULL DEFAULT 4326 CHECK (srid = 4326),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS routes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL CHECK (length(trim(name)) > 0),
  color CHAR(7) NOT NULL DEFAULT '#edb73f'
    CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
  geometry_geojson JSONB NOT NULL
    CHECK (geometry_geojson ->> 'type' = 'LineString'),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS route_stops (
  route_id BIGINT NOT NULL REFERENCES routes(id) ON DELETE CASCADE,
  stop_id BIGINT NOT NULL REFERENCES bus_stops(id) ON DELETE RESTRICT,
  stop_order SMALLINT NOT NULL CHECK (stop_order > 0),
  PRIMARY KEY (route_id, stop_id),
  UNIQUE (route_id, stop_order)
);

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(32) NOT NULL,
  password_hash TEXT NOT NULL,
  full_name VARCHAR(100) NOT NULL CHECK (length(trim(full_name)) > 0),
  age SMALLINT NOT NULL CHECK (age BETWEEN 1 AND 120),
  gender TEXT NOT NULL CHECK (
    gender IN ('male', 'female', 'other', 'prefer_not_to_say')
  ),
  phone_e164 VARCHAR(16) NOT NULL UNIQUE,
  phone_verified_at TIMESTAMPTZ,
  auth_version INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS auth_version INTEGER NOT NULL DEFAULT 0;

ALTER TABLE users
  ALTER COLUMN phone_verified_at DROP NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower_key
  ON users (lower(username));

CREATE TABLE IF NOT EXISTS auth_sms_rate_limits (
  identifier_hash CHAR(64) NOT NULL,
  purpose TEXT NOT NULL CHECK (purpose IN ('registration', 'password_reset')),
  window_started_at TIMESTAMPTZ NOT NULL,
  send_count SMALLINT NOT NULL CHECK (send_count BETWEEN 1 AND 5),
  next_allowed_at TIMESTAMPTZ NOT NULL,
  PRIMARY KEY (identifier_hash, purpose)
);

CREATE TABLE IF NOT EXISTS auth_login_rate_limits (
  identifier_hash CHAR(64) PRIMARY KEY,
  window_started_at TIMESTAMPTZ NOT NULL,
  attempt_count SMALLINT NOT NULL CHECK (attempt_count BETWEEN 1 AND 10)
);

CREATE TABLE IF NOT EXISTS user_locations (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
  longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
  accuracy_meters DOUBLE PRECISION CHECK (
    accuracy_meters IS NULL OR accuracy_meters >= 0
  ),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS user_locations_updated_at_idx
  ON user_locations (updated_at);

CREATE TABLE IF NOT EXISTS user_waiting_stops (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  stop_id BIGINT NOT NULL REFERENCES bus_stops(id) ON DELETE CASCADE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS user_waiting_stops_stop_updated_idx
  ON user_waiting_stops (stop_id, updated_at);
